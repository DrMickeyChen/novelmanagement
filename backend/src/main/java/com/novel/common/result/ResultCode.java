package com.novel.common.result;

import lombok.Getter;

/**
 * 统一错误码。
 *
 * <p>分段规则见 {@code 项目大纲.md §6.2}：
 * <pre>
 *   200        成功
 *   400 ~ 500  通用 HTTP 语义错误
 *   1001 ~     用户模块
 *   2001 ~     小说模块
 *   3001 ~     章节模块
 *   4001 ~     评论模块
 *   5001 ~     AI 模块
 *   6001 ~     分类模块
 *   7001 ~     公告模块
 *   9001 ~     系统/中间件（第二期用）
 * </pre>
 *
 * <p><b>为什么要分段而不是随便给号：</b>前端可以只判断区段就决定怎么处理 ——
 * 比如 {@code 401} 直接踢回登录页、{@code 1xxx} 提示「账号相关」、
 * {@code 2xxx} 提示「作品相关」，不用为每个错误码写一个 if。
 *
 * <p><b>★★ 这个分段还有一个用途：决定 HTTP 状态码。</b>
 * 前两段（400~599）和 HTTP 语义<b>一一对应</b>，所以它们会被原样
 * 写进 HTTP 状态码；{@code 1001+} 是纯业务语义，HTTP 里没有对应物，
 * 一律返 200，错误码只放 body。
 * <pre>
 *   ResultCode.PARAM_ERROR(400)      → HTTP 400
 *   ResultCode.UNAUTHORIZED(401)     → HTTP 401
 *   ResultCode.USER_PASSWORD_ERROR(1002) → HTTP 200（正常业务结果，不是故障）
 * </pre>
 * ★ <b>所以新增错误码之前想清楚它该放哪个区段</b> ——
 * 「未登录/无权限/资源不存在」这类必须用 401/403/404，
 * 一旦放成 1001+ 就失去了监控可见性，而且和已有的 401 语义打架。
 * 翻译规则在 {@link ResultHttpStatus}。
 *
 * @author MickeyChen
 */
@Getter
public enum ResultCode {

    /* ---------- 通用 ---------- */
    SUCCESS(200, "操作成功"),
    PARAM_ERROR(400, "参数校验失败"),
    UNAUTHORIZED(401, "未登录或登录已过期"),
    FORBIDDEN(403, "没有操作权限"),
    NOT_FOUND(404, "请求的资源不存在"),
    METHOD_NOT_ALLOWED(405, "请求方法不支持"),
    SYSTEM_ERROR(500, "服务器开小差了，请稍后再试"),

    /* ---------- 用户模块 1001 ~ ---------- */
    USER_NOT_FOUND(1001, "用户不存在"),
    USER_PASSWORD_ERROR(1002, "用户名或密码错误"),
    USER_DISABLED(1003, "账号已被禁用"),
    USERNAME_EXISTS(1004, "用户名已被注册"),
    EMAIL_EXISTS(1005, "邮箱已被注册"),
    TOKEN_INVALID(1006, "登录凭证无效"),
    TOKEN_EXPIRED(1007, "登录已过期，请重新登录"),
    OLD_PASSWORD_ERROR(1008, "原密码不正确"),
    AUTHOR_APPLY_PENDING(1009, "作者申请审核中，请耐心等待"),
    NOT_AUTHOR(1010, "你还不是作者，请先申请成为作者"),
    /*
     * ★ 1001~1010 是 P1 定的十连号，P5 从 1011 接着往下排：
     *   1011~1013 → S6（用户管理），1014~1016 → S11（作者申请），
     *   1017 起 → S13（角色 / 菜单）。
     *   ★ 分段的规矩是「不重复」，不是「预留」—— 早先的排期里写过
     *     「1014 起留给 S13」，那是在 S11 还没定号的时候写的；
     *     S11 先落地就先占号，S13 顺延，比留一个空洞更好读。
     */
    ROLE_NOT_FOUND(1011, "角色不存在"),
    /*
     * ★★ 下面这两个是【防自锁】用的，不是权限校验。
     *
     * 管理员封禁自己 = 把自己踢出登录，而且再也登不回来
     * （AuthServiceImpl 的 status 检查会返回 1003）——
     * 恢复只能进 MySQL 手工改 status。
     * 同理，把自己身上的 ADMIN 角色拿掉 = 左侧菜单里的「用户管理」
     * 「角色管理」全部消失，再也没法从界面上加回来。
     *
     * 这和 D-6 的「角色权限树自锁」是同一类问题：**UI 操作造成不可逆损害**。
     * 拦它们的成本各自只有几行判断，中招之后的恢复成本是「连数据库」。
     */
    USER_CANNOT_BAN_SELF(1012, "不能封禁自己的账号，否则你将无法再登录"),
    USER_CANNOT_REMOVE_OWN_ADMIN(1013, "不能移除自己的管理员角色，否则你将无法再进入管理端"),

    /*
     * ★★ 作者申请（P5 的 S11）。三个码【刻意留在 1000 段】而不是另起一段：
     *   作者申请改的是「用户的角色」，出错的地方是「进不进得去创作中心」，
     *   和 USER_DISABLED / NOT_AUTHOR 是同一类提示 —— 前端拿到 1xxx
     *   就该在「账号相关」的位置弹，不用为它多学一段号码。
     *   （1014 和 1016 是「东西不存在 / 状态不对」，本来也不必新造 ——
     *     但 2001 / 3001 / 4001 各自属于作品 / 章节 / 评论，
     *     借过来会让「2xxx = 作品相关」这条规则出现例外。）
     */
    AUTHOR_APPLY_NOT_FOUND(1014, "作者申请不存在"),
    /*
     * ★ 注意它和 AUTHOR_APPLY_PENDING(1009) 是【两个方向】：
     *   1009 = 你已经交过一份了，还在审，等着；
     *   1015 = 你已经是作者了，别再交了。
     *   合并成一个「不能重复申请」的话，两种情况的下一步动作完全不同
     *   （一个要等，一个什么都不用做），提示就没法指导用户。
     */
    AUTHOR_APPLY_ALREADY_AUTHOR(1015, "你已经是作者了，无需重复申请"),
    /*
     * ★ 和 COMMENT_STATUS_ILLEGAL(4005) / NOVEL_STATUS_ILLEGAL 同一个形态。
     *   触发它的只有一种情况：申请的终态已经定了（通过 / 驳回），
     *   但管理员想把它改成【另一个】终态 —— 驳回过的不能追认通过。
     *   ★ 「再点一次同样的按钮」不走这个码，那是幂等的（见 AuthorApplyService#audit）。
     */
    AUTHOR_APPLY_STATUS_ILLEGAL(1016, "当前申请状态不允许该操作"),

    /*
     * ★★ 角色 / 菜单（P5 的 S13）。1017~1021 是紧接着 1016 排下来的。
     *
     * 这一段里 1018 / 1020 是【防自锁】，不是常规校验 —— 它们拦的是
     * 「管理员一个 UI 操作把自己永久关在门外」这件事。和 1012 / 1013
     * （不能封禁自己、不能移除自己的 ADMIN）是同一类，只是这次的战场
     * 换成了「角色能看哪些菜单」。理由见 docs/P5-管理后台.md 的 D-6。
     */
    ROLE_CODE_EXISTS(1017, "角色标识已存在"),

    /*
     * ★★ 内置角色（ADMIN / AUTHOR / READER）禁止删除、停用、改标识。
     *
     * 这三件事各能造成一次【全局性】故障，且都不可逆（停用/删除后
     * 界面上再也改不回来）：
     * <pre>
     *   删 ADMIN  → 所有管理员同时失去管理端权限，谁也进不来
     *   停 ADMIN  → 同上的效果，因为 selectRoleCodesByUserId 带 status = 1
     *   改 ADMIN 的 role_code → CommonConstant.ROLE_ADMIN 的所有判断全部落空，
     *                            SecurityConfig 的 hasRole("ADMIN") 从此无人满足
     * </pre>
     * 另外 {@code uk_role_code} 唯一索引【不含 deleted】，逻辑删掉之后
     * 这个码再也建不回来 —— 删内置角色的代价是「重新灌种子数据」。
     *
     * ★ 用独立错误码而不复用 ROLE_NOT_FOUND(1011)：两者对管理员意味着
     *   完全不同的下一步。「角色不存在」= 刷新一下列表；「内置角色不能删」
     *   = 换个做法，这条规则本身不会变。
     */
    ROLE_BUILTIN(1018, "内置角色（ADMIN / AUTHOR / READER）不允许删除、停用或修改标识"),

    /*
     * ★ 该角色下还挂着用户，删除会留下【悬空关联】。
     *   那行 sys_user_role 还在，但 join 不到角色 —— 那个用户登录后
     *   roles 是空数组，表现是「登录成功但什么页面都进不去」，
     *   而界面上完全看不出原因（见 AdminUserServiceImpl 里同类注释）。
     *
     * ★ 这里选择【拒绝】而不是「级联删掉关联」，和 sys_role_menu 的处理相反
     *   （那个是级联清理）。区别在于后果：菜单关联没了无非是权限少了，
     *   而用户的角色没了是「这个人被废掉」—— 不该由「删一个角色」顺手完成。
     */
    ROLE_IN_USE(1019, "该角色下还有用户，请先把这些用户改到别的角色再删除"),

    /*
     * ★★ 自锁防护：不能把【自己所属角色】上的「角色管理 / 菜单管理」菜单去掉。
     *
     * 去掉之后保存成功 → 左侧菜单里这两项立刻消失（菜单是按权限点过滤的）
     * → 而权限只在下次登录时重新查库，所以这里同时会把你自己踢下线
     * → 重新登录后，你【再也看不到】任何一个能改回来的界面。
     * 恢复方式只剩进 MySQL 手工 INSERT sys_role_menu。
     *
     * ★ 这是本项目里唯一一处「UI 上的正常操作能造成不可逆损害」的地方，
     *   所以宁可拦错也不能漏 —— 见 AdminRoleServiceImpl#guardSelfLock。
     */
    ROLE_SELF_MENU_LOCK(1020, "不能去掉你自己角色上的「角色管理 / 菜单管理」，否则你将无法再改回来"),

    /*
     * ★ 赋菜单时传了一个不存在的 menuId。
     *   不校验的话会在 sys_role_menu 里留下【悬空行】：它不影响任何鉴权
     *   （权限查询 join 不到菜单就自动忽略），所以不会报错、不会被发现，
     *   只会在「这个角色到底被授了什么」这个问题上永远给出一个假的答案。
     */
    MENU_NOT_FOUND(1021, "菜单不存在"),

    /* ---------- 小说模块 2001 ~ ---------- */
    NOVEL_NOT_FOUND(2001, "作品不存在"),
    NOVEL_NOT_YOURS(2002, "这不是你的作品"),
    NOVEL_STATUS_ILLEGAL(2003, "当前作品状态不允许该操作"),
    NOVEL_NOT_PUBLISHED(2004, "作品尚未上架"),
    NOVEL_HAS_CHAPTERS(2005, "作品下已有章节，无法删除"),

    /* ---------- 章节模块 3001 ~ ---------- */
    CHAPTER_NOT_FOUND(3001, "章节不存在"),
    CHAPTER_NOT_YOURS(3002, "这不是你作品的章节"),
    CHAPTER_STATUS_ILLEGAL(3003, "当前章节状态不允许该操作"),
    CHAPTER_NUMBER_EXISTS(3004, "该章节序号已存在"),
    CHAPTER_CONTENT_EMPTY(3005, "章节正文不能为空"),

    /*
     * 大纲树（P4）。★ 和章节共用 3xxx 段而不是另起一段：
     * 大纲树是「章节的上游」—— 它是章节的写作计划，不是独立业务对象。
     * 而且它和章节一样只在创作中心一个地方出现，前端拿到 3xxx
     * 就知道该在当前页面提示，不用再学一段新号码。
     */
    OUTLINE_NODE_NOT_FOUND(3006, "大纲节点不存在"),
    OUTLINE_NODE_NOT_YOURS(3007, "该大纲节点不属于这本作品"),
    OUTLINE_ROOT_EXISTS(3008, "这本作品已经有根节点了"),
    /*
     * ★ 3009 和 3010 的区别是【责任方】：
     *   3009 = 用户做了非法操作（把父节点拖进自己的子孙里）→ 提示他改操作
     *   3010 = 库里的数据本来就是坏的（已经存在环）→ 提示他刷新，且必须 log.error
     * 合成一个码的话，数据坏掉时会提示「不能移动到自己的子节点下」，
     * 而用户根本没做这件事 —— 他会反复重试，而日志上一条异常都没有。
     */
    OUTLINE_PARENT_ILLEGAL(3009, "不能把节点移动到它自己的子节点下"),
    OUTLINE_TREE_BROKEN(3010, "大纲结构异常，请刷新后重试"),
    OUTLINE_TOO_DEEP(3011, "大纲层级过深（最多 20 层）"),

    /* ---------- 评论模块 4001 ~ ---------- */
    COMMENT_NOT_FOUND(4001, "评论不存在"),
    COMMENT_NOT_YOURS(4002, "只能删除自己的评论"),
    COMMENT_ALREADY_DELETED(4003, "评论已被删除"),
    COMMENT_TOO_FAST(4004, "评论太频繁了，休息一下吧"),
    /*
     * ★ P5（S9）补的，和 NOVEL_STATUS_ILLEGAL / CHAPTER_STATUS_ILLEGAL 同名同构。
     *
     * 触发它的只有一种情况：目标状态和当前状态之间没有边
     * （CommentStatus.canTransitTo 返回 false）。最常见的两种是
     * 「对一条已显示的评论再点一次通过」和「对一个已隐藏的评论再点一次隐藏」——
     * ★ 这类重复提交【刻意返回错误而不是静默成功】，
     *   和 NovelService/ChapterService 的 transitStatus 行为一致。
     *   静默成功会让管理员以为刚才那一下没点上，然后再点一次。
     */
    COMMENT_STATUS_ILLEGAL(4005, "当前评论状态不允许该操作"),

    /* ---------- AI 模块 5001 ~ ---------- */
    AI_DISABLED(5001, "AI 功能未启用"),
    AI_API_KEY_MISSING(5002, "尚未配置 AI 的 API Key"),
    AI_CALL_FAILED(5003, "AI 服务调用失败，请稍后重试"),
    AI_QUOTA_EXCEEDED(5004, "今日 AI 额度已用完"),

    /* ---------- 分类模块 6001 ~ ---------- */
    /*
     * 分类单独占一段（而不是塞进上面的「小说模块 2001~」）：
     * 分段解决的是「前端拿到错误码后该在哪个页面提示」——
     * 分类的错误全部发生在分类管理页，和小说/章节的错误不在一个页面上。
     *
     * ★ 注意 6001 不在 400~599 里，所以它返的是 HTTP 200（见 ResultHttpStatus）——
     * 「分类不存在」是正常的业务结果，不是协议层故障，不该在监控上报警。
     */
    CATEGORY_NOT_FOUND(6001, "分类不存在"),
    CATEGORY_NAME_EXISTS(6002, "分类名称已存在"),
    CATEGORY_HAS_NOVELS(6003, "该分类下还有作品，无法删除"),

    /* ---------- 公告模块 7001 ~ ---------- */
    /*
     * ★★ 这一段【只有一条】，和上面分类段的 3 条、角色段的 5 条形成对比，
     *    这不是「没做完」，是公告这个功能的错误面本来就这么小：
     * <pre>
     *   没有「重名」  —— 公告标题【没有唯一约束】，也不该有。
     *                    「系统维护通知」一年要发好几次，标题重复是正常的，
     *                    给它加唯一键会逼着运营在标题后面缀日期。
     *   没有「状态非法」—— 公告没有状态机。发布 / 下线 / 再发布 / 再下线
     *                    是自由的，重复执行同一个动作都是幂等的
     *                    （对照 Novel / AuthorApply 那些真的有边界的流转）。
     *   没有「被引用」  —— 公告不挂在任何别的东西上，删了就是删了。
     * </pre>
     * ★ 空参数（标题超长、内容为空、type 传了 3）全部由 {@code NoticeSaveDTO}
     *   上的校验注解拦成 HTTP 400 —— 那是【请求格式错误】，不是业务失败，
     *   不该占一个 7xxx 的号（分段规则见本类开头，400~599 与 HTTP 一一对应）。
     *
     * ★ 注意 7001 不在 400~599 里，所以它返的是 HTTP 200（见 ResultHttpStatus）——
     * 「公告不存在」是正常的业务结果（多半是别人已经删了、你的页面是旧的），
     * 不是协议层故障。
     */
    NOTICE_NOT_FOUND(7001, "公告不存在");

    /** 错误码 */
    private final Integer code;

    /** 给用户看的提示语（不要写技术细节，直接能弹到前端） */
    private final String message;

    ResultCode(Integer code, String message) {
        this.code = code;
        this.message = message;
    }
}
