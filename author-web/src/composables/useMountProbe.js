import { ref } from 'vue'

/**
 * 组件挂载计数器 —— **验收工具，不是业务代码**。
 *
 * ------------------------------------------------------------
 * ★ 它为什么存在
 * ------------------------------------------------------------
 * P4 的验收原话是「**切换节点时大纲树纹丝不动**」。这句话靠肉眼看是
 * 不可靠的：重挂载造成的闪烁只有几十毫秒，滚动位置跳回顶部也可能被
 * 当成「我记错了刚才滚到哪」。而「树到底有没有被重建」是一个**确定的
 * 事实**，应该有确定的验证方式。
 *
 * 有了这个计数器，验收从「盯着看有没有闪」变成「看一眼数字有没有变」：
 * 在树的节点之间来回切换，`WorkLayout` 的挂载次数**必须停在 1**。
 * 变成 2、3、4 就说明树被重建了 —— 那正是 D-1 里说的「大纲树挂错层」。
 *
 * ------------------------------------------------------------
 * ★ 为什么带 DEV 开关
 * ------------------------------------------------------------
 * 它对用户没有任何价值，不该出现在生产构建里。
 * `import.meta.env.DEV` 在生产构建时是 `false`，Vite 会把这个分支
 * **整段摇掉**（tree-shaking），所以生产包里连这个文件都不会被引用。
 *
 * ------------------------------------------------------------
 * ★ 实现上唯一一处要注意的：计数必须存在【模块级】
 * ------------------------------------------------------------
 * 如果 `counts` 定义在函数体里，每次组件挂载都会新建一个 ref，
 * 计数永远是 1 —— 一个永远显示「没问题」的计数器，比没有更糟。
 * 放在模块顶层，整个页面生命周期内只有一份，重挂载才会累加。
 */
const counts = ref({})

/**
 * 记一次挂载，返回全局计数。
 *
 * ★ 在 `<script setup>` 的顶层直接调用即可 —— setup 体每次组件实例化都会执行，
 *   所以「调用次数」就等于「挂载次数」。
 *
 * @param {string} name 组件名，用来在界面上区分
 * @returns {import('vue').Ref<Object>} 名字 → 挂载次数
 */
export function useMountProbe(name) {
  if (import.meta.env.DEV) {
    counts.value[name] = (counts.value[name] || 0) + 1
  }
  return counts
}

/** 手动归零。调试时想重新数一遍用，界面上没挂按钮 */
export function resetMountProbe() {
  counts.value = {}
}
