/**
 * 作者申请管理接口 —— 对应后端 AdminAuthorApplyController（/api/admin/author-applies）。
 *
 * ------------------------------------------------------------
 * ★★ 「通过」不是一个状态位，是【真的给权限】
 * ------------------------------------------------------------
 * 后端在通过时会做三件事，缺一不可：
 *   ① 改 `author_apply.status`
 *   ② 往 `sys_user_role` 插一行 AUTHOR
 *   ③ `tokenStore.removeAll(userId)` 把申请人踢下线
 *
 * 只做 ① 的话，用户会看到「已通过」但**进不去创作中心**
 * （`SecurityConfig` 的 `hasAnyRole("AUTHOR","ADMIN")` 会拦下），
 * 而两个界面看起来都正常 —— 这是这个模块最典型的半成品 bug。
 *
 * ③ 容易被漏掉但同样必须：角色和权限是**登录时**写进 Redis 的，
 * 不踢的话申请人重新打开创作中心照样被拒，而他看到的提示是
 * 「你还不是作者」。所以界面上必须告诉管理员「该用户需要重新登录」。
 *
 * ------------------------------------------------------------
 * ★★ 接口形状和评论审核【不一样】，别照着 api/comment.js 抄
 * ------------------------------------------------------------
 *   评论：`PUT /admin/comments/{id}/status`  body `{ status, remark }` ← 目标状态码
 *   申请：`PUT /admin/author-applies/{id}/audit`  body `{ pass, remark }` ← 布尔
 *
 * 两条路都合理，各有各的理由：评论的**可逆**（已显示 ↔ 已隐藏，
 * 两个方向都是合法转移），所以用「目标状态」表达更自然；
 * 而申请是**单向**的（待审 → 通过/驳回，终态之间没有边），
 * 用布尔「通过还是驳回」就是在说这件事本身。
 *
 * ------------------------------------------------------------
 * ★★ 四种结果，前端要分开对待
 * ------------------------------------------------------------
 *   200  成功（**首次**审核：改了状态、通过了就真的授了角色并踢了人）
 *   200  **重复**审核同一个结果 —— 幂等。但注意：第二击**不会**再授角色、
 *        也不会再踢人（后端的幂等 return 在授权之前）。所以页面上把这类
 *        按钮禁掉了，不是因为它会报错，而是因为它**什么都不做却弹一句
 *        「已通过，需重新登录才生效」** —— 那是一句假话。
 *   1016 把「已驳回」改成「已通过」（或反过来）。**终态之间没有边**，
 *        要重来请让申请人重新提交一份。界面上同样不可达（只有待审行可审），
 *        但后端必须留着 —— 两个管理员同时打开同一行时，它拦的是第二个。
 *   1014 申请不存在（并发下被别人删了）
 *
 * ------------------------------------------------------------
 * ★★ 成功文案到不了前端
 * ------------------------------------------------------------
 * 后端 `Result.success("已通过，该用户已获得作者权限，需重新登录后生效")` 里
 * 那句 message，在**成功路径上会被 request.js 的拦截器吃掉**（它只返回 `data`，
 * 而且对 `code === 200` 不弹任何提示 —— 它只弹错误）。
 * 所以页面里的成功提示必须在**前端再写一遍**。
 * 两处的说法要一起改：只说「已通过」不提「需重新登录」的话，管理员
 * 会以为没生效而再点一次（而第二击什么都不做）。
 */
import request from '@/utils/request'

/**
 * 作者申请列表（分页）。
 *
 * @param {object} params
 * @param {number} [params.status] 0 待审 / 1 已通过 / 2 已驳回。★ 不传 = 全部
 *   （传 `null` 而不是空串：axios 会跳过 null/undefined 参数，正好对上
 *     后端「不传 = 全部」；传空串会变成 `?status=`，后端转 Integer 会失败）
 *   ★ 传别的数字（比如 9）后端返回 **400**，不是静默列出全部 ——
 *     筛选写错时看到的是报错，而不是「筛选没生效」
 * @param {string} [params.keyword] **笔名 / 申请人用户名 / 昵称**的模糊匹配
 * @param {number} [params.page]
 * @param {number} [params.size] 上限 100（后端 PaginationInnerInterceptor 夹的）
 * @returns {Promise<{records: Array, total: number}>}
 *   ★ 排序是 **状态升序 + id 倒序**：待审的在最前面（这是一条**待办队列**，
 *     不是档案页），同状态内最新提交的在前。所以**不传 status 时的默认视图
 *     就是「今天有活吗」**，不需要额外加一个「只看待审」的开关。
 *   ★ 每条带 `status`（数字，用来判断）和 `statusDesc`（中文，用来显示）
 *     —— 和作品/章节/评论同一条规矩：**判断用数字，显示用 Desc**。
 *   ★ 带 `username` 和 `nickname`。**两个都为空说明申请人已注销**
 *     （JSON 里这两个 key 会整个消失，全局 `default-property-inclusion: non_null`），
 *     判定写 `row.username`，**不要写 `=== null`**。
 *   ★ **不含** `auditUserId` —— 要看「谁审的」去审核日志页。
 */
export function getAuthorApplyPage(params) {
  return request.get('/admin/author-applies', { params })
}

/**
 * 审核作者申请：通过（同时授予 AUTHOR 角色 + 踢下线）或驳回。
 *
 * @param {number} id 申请 id
 * @param {boolean} pass `true` 通过 / `false` 驳回
 * @param {string} [remark] ≤255 字。
 *   ★★ **驳回时是给申请人看的理由** —— 读者端
 *   `GET /api/reader/author-apply/mine` 会把它原样返回。
 *   这一点和评论的 `auditRemark`（管理员自留备注，读者看不到）**正好相反**，
 *   所以这一页的驳回理由**必填**（`remarkRequired = true`），
 *   而评论那页是可选的。别把两边的规矩抄混。
 *   ★ 通过时的 remark 也会写进 `audit_log`，但申请人看不到「通过理由」
 *   （读者端只在被驳回时才需要那句话）。
 *
 * ★ 通过后**申请人会被强制下线**，他必须重新登录才能进创作中心。
 *
 * ★ 审核记录会写进 `audit_log`（`targetType = 4 作者申请`），
 *   在「审核日志」页查得到，标题显示成 **「笔名（昵称）」**。
 *   （★ 不是「作者申请 #5」那种编号 —— 流水表存的是**申请 id**不是 user id，
 *     所以后端专门做了 apply_id → user_id → nickname 两跳来补这个标题。）
 */
export function auditAuthorApply(id, pass, remark) {
  return request.put(`/admin/author-applies/${id}/audit`, { pass, remark })
}
